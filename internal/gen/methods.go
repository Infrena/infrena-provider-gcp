package gen

import (
	"bytes"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/infrena/infrena-provider-gcp/internal/disco"
)

// RenderMethods is gen/methods.tsv: every Discovery method as the fake's
// round trip needs it -- the verb, the address (flatPath where the document
// has one), how it answers, and the query parameters it requires.
//
// schemas/ is gitignored and fetched, so a test that read it passed on one
// laptop and failed in every clean checkout (CI, 2026-09-25). This is the
// committed digest of the documents the catalog was generated from, the way
// operation parameter patterns became committed data before it.
func RenderMethods(schemaDir string) ([]byte, error) {
	docs, err := loadDocs(schemaDir)
	if err != nil {
		return nil, err
	}
	var lines []string
	for _, d := range docs {
		for _, col := range d.Collections() {
			for _, m := range col.Methods {
				path := m.FlatPath
				if path == "" {
					path = m.Path
				}
				kind, _ := AwaitOf(d, m)
				var required []string
				for name, p := range m.Parameters {
					if p.Location == "query" && (p.Required ||
						disco.Behaviors(&disco.Schema{Description: p.Description})[disco.BehaviorRequired]) {
						required = append(required, name)
					}
				}
				sort.Strings(required)
				lines = append(lines, fmt.Sprintf("%s\t%s\t%s\t%s\t%s\t%s",
					d.Name, m.HTTPMethod, path, awaitName(kind), strings.Join(required, ","), m.ID))
			}
		}
	}
	sort.Strings(lines)
	var b bytes.Buffer
	b.WriteString("# Every Discovery method the catalog's documents publish. GENERATED by cmd/gen-gcp.\n")
	b.WriteString("# service\tverb\tpath\tanswers\trequired_query\tid\n")
	for _, l := range lines {
		b.WriteString(l + "\n")
	}
	return b.Bytes(), nil
}

// WriteMethods writes RenderMethods to path.
func WriteMethods(schemaDir, path string) error {
	data, err := RenderMethods(schemaDir)
	if err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}
