const banner = "<!-- GENERATED by cmd/gen-docs from the embedded catalog. Do not edit by hand. -->"

// Pages renders the whole reference. Keys are slash-separated paths relative to
// the output root.
func Pages(c *catalog.Catalog, ws []warning) map[string]string {
	byService := map[string][]*catalog.Type{}
	for _, t := range c.Types {
		byService[t.Service] = append(byService[t.Service], t)
	}
	services := make([]string, 0, len(byService))
	for s, ts := range byService {
		services = append(services, s)
		sort.Slice(ts, func(i, j int) bool { return ts[i].Name < ts[j].Name })
	}
	sort.Strings(services)

	pages := map[string]string{
		"README.md":      renderIndex(c, services, byService, ws),
		"not-shipped.md": renderNotShipped(ws),
	}
	for _, s := range services {
		pages[s+"/README.md"] = renderService(s, byService[s])
		for _, t := range byService[s] {
			pages[s+"/"+t.Name+".md"] = renderType(t)
		}
	}
	return pages
}

func renderIndex(c *catalog.Catalog, services []string, byService map[string][]*catalog.Type, ws []warning) string {
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	p("%s\n\n# GCP type reference\n\n", banner)
	p("This plugin serves **%d types** across %d Google Cloud services. ", len(c.Types), len(services))
	p("Every page below is generated from the catalog the plugin itself loads, so it says what the plugin does, not what it intends to do.\n\n")
	p("- Catalog generated: %s\n", c.Generated)
	p("- From magic-modules commit: `%s`\n\n", c.MMV1Commit)
	p("**[Types that are not served, and why](not-shipped.md)** — %d entries. ", countNotShipped(ws))
	p("Read that page first if the type you want is missing from this one.\n\n")

	p("## Services\n\n")
	p("| Service | Types |\n| --- | --- |\n")
	for _, s := range services {
		p("| [%s](%s/README.md) | %d |\n", s, s, len(byService[s]))
	}

	p("\n## How to read a type page\n\n")
	p("- **What it can do** is derived from the catalog the same way `infrena explain` derives it. ")
	p("A type whose create url has a placeholder nothing can fill reports `create: no`, and the page names the placeholder.\n")
	p("- **Attributes** lists every attribute at every depth. A `.` is a field of an object; a `[]` is the element of a list. ")
	p("Both are real nesting edges in the catalog and both are followed here.\n")
	p("- **Also spelled** lists the alternative spellings configuration accepts for an attribute, ")
	p("including the snake_case alias emitted for every camelCase name.\n")
	p("- **Set by** is `required` (you must write it), `optional` (you may) or `output only` (GCP chooses it; configuration may not set it).\n")
	p("- A note of `same fields as x.y` means the attribute's subtree is identical to one already listed on the page. ")
	p("Several GCP schemas are recursive, and expanding them twice would repeat thousands of identical rows.\n")
	return b.String()
}

func countNotShipped(ws []warning) int {
	n := 0
	for _, w := range ws {
		if w.Tier != "nocreate" {
			n++
		}
	}
	return n
}

func renderService(service string, ts []*catalog.Type) string {
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	p("%s\n\n# %s\n\n", banner, service)
	p("%d type(s). [Back to the index](../README.md).\n\n", len(ts))
	p("| Type | Create | Update | Import | What it is |\n| --- | --- | --- | --- | --- |\n")
	for _, t := range ts {
		p("| [`%s`](%s.md) | %s | %s | %s | %s |\n",
			t.Name, t.Name,
			yesNo(canCreate(t)), yesNo(t.UpdateVerb != ""), yesNo(t.ImportFormat != ""),
			cell(firstSentence(t.Description), 140))
	}
	return b.String()
}

func renderType(t *catalog.Type) string {
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	p("%s\n\n# `%s`\n\n", banner, t.Name)
	if d := flatten(t.Description); d != "" {
		p("%s\n\n", d)
	}
	p("[%s](README.md) · [all services](../README.md)\n\n", t.Service)

	p("| | |\n| --- | --- |\n")
	p("| Service | %s |\n", t.Service)
	p("| Scope | %s |\n", scopeName(t.Scope))
	if t.AssetType != "" {
		p("| Asset type | `%s` |\n", t.AssetType)
	}
	if t.ParentRoot != "" {
		p("| Hangs off | `%s` |\n", t.ParentRoot)
	}
	p("| Tier | %d%s |\n", t.Tier, paren(t.TierReason))
	p("| Mutation timeout | %ds |\n", t.TimeoutSeconds)

	p("\n## What it can do\n\n")
	p("| Operation | Supported | How |\n| --- | --- | --- |\n")
	missing := t.UnresolvedCreatePlaceholders()
	createHow := "`POST " + code(t.CreateTemplate()) + "`"
	if len(missing) > 0 {
		createHow = "the create url `" + code(t.CreateTemplate()) + "` needs " +
			list(missing) + ", which nothing supplies: no provider setting (project, region, zone, location), " +
			"no stored binding, and no settable attribute of this type"
	}
	p("| Create | %s | %s |\n", yesNo(len(missing) == 0), createHow)
	readHow := "`GET " + code(orElse(t.SelfLink, t.BaseURL)) + "`"
	if t.ReadVia != "" {
		readHow = "by `" + t.ReadVia + "`: " + readHow
	}
	p("| Read | yes | %s |\n", readHow)
	updateHow := ""
	if t.UpdateVerb != "" {
		updateHow = "`" + t.UpdateVerb + " " + code(orElse(t.UpdateURL, orElse(t.SelfLink, t.BaseURL))) + "`"
		if t.UpdateVerb == "PUT" {
			updateHow += ", the whole resource: read first, with the change written in"
		}
		if t.UpdateMask {
			updateHow += ", with an update mask naming the changed fields"
		}
	} else {
		updateHow = "publishes no update method; every change to it replaces the resource"
	}
	p("| Update | %s | %s |\n", yesNo(t.UpdateVerb != ""), updateHow)
	p("| Delete | yes | `DELETE %s` |\n", code(orElse(t.DeleteURL, orElse(t.SelfLink, t.BaseURL))))
	importHow := "no import id shape is published for this type"
	if t.ImportFormat != "" {
		importHow = "by id, see below"
	}
	p("| Import | %s | %s |\n", yesNo(t.ImportFormat != ""), importHow)

	p("\n## Import id\n\n")
	if t.ImportFormat == "" {
		p("This type cannot be imported: magic-modules publishes no id shape for it.\n")
	} else {
		forms := strings.Split(t.ImportFormat, "\n")
		if len(forms) == 1 {
			p("```\n%s\n```\n", strings.TrimSpace(forms[0]))
		} else {
			p("Any one of these shapes is accepted, tried in order:\n\n```\n")
			for _, f := range forms {
				if f = strings.TrimSpace(f); f != "" {
					p("%s\n", f)
				}
			}
			p("```\n")
		}
	}

	p("\n## Attributes\n\n")
	rows := attrRows(t)
	p("%d attribute(s), at every depth. A `.` is a field of an object; `[]` is the element of a list.\n\n", len(rows))
	p("| Attribute | Also spelled | Type | Set by | Notes | Description |\n")
	p("| --- | --- | --- | --- | --- | --- |\n")
	for _, r := range rows {
		p("| `%s` | %s | %s | %s | %s | %s |\n",
			r.Path, r.spellings(), "`"+r.Attr.Kind.String()+"`", setBy(r.Attr), r.notes(), cell(flatten(r.Attr.Description), 200))
	}

	if refs := refRows(rows); len(refs) > 0 {
		p("\n## References\n\n")
		p("These attributes name another type. infrena uses them to order a plan.\n\n")
		p("| Attribute | Points at |\n| --- | --- |\n")
		for _, r := range refs {
			p("| `%s` | `%s.%s` |\n", r.Path, r.Attr.Ref.Type, r.Attr.Ref.Attribute)
		}
	}
	return b.String()
}

func renderNotShipped(ws []warning) string {
	var b strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	p("%s\n\n# Types this plugin does not serve\n\n", banner)
	p("If a GCP resource is not in the [reference](README.md), it is on this page with the reason. ")
	p("There is no third list.\n\n")
	p("Every candidate type is sorted into a tier before anything is generated:\n\n")
	p("- **tier 1** ships as it stands.\n")
	p("- **tier 2** has provider-side wire hooks — custom import, an encoder, a pre-update step — that change what goes on the wire. ")
	p("A tier-2 type ships only once somebody writes a ruling in `gen/overlay.yaml` that names **every** hook on it and says what each one does. ")
	p("Naming most of them is not enough: an unnamed hook is behaviour this plugin would silently not perform.\n")
	p("- **tier 3** is not representable at all — no create method, no delete method, beta-only, or excluded upstream.\n\n")
	p("So a type listed under \"unruled wire hooks\" below is not impossible. It is unwritten. ")
	p("The hooks named on its row are exactly what a ruling has to account for.\n\n")

	var shipped, notShipped []warning
	for _, w := range ws {
		if w.Tier == "nocreate" {
			shipped = append(shipped, w)
			continue
		}
		notShipped = append(notShipped, w)
	}

	groups := map[string][]warning{}
	for _, w := range notShipped {
		groups[category(w.Reason)] = append(groups[category(w.Reason)], w)
	}
	names := make([]string, 0, len(groups))
	for n := range groups {
		names = append(names, n)
	}
	sort.Slice(names, func(i, j int) bool {
		if len(groups[names[i]]) != len(groups[names[j]]) {
			return len(groups[names[i]]) > len(groups[names[j]])
		}
		return names[i] < names[j]
	})

	p("## Summary\n\n| Reason | Types |\n| --- | --- |\n")
	for _, n := range names {
		p("| [%s](#%s) | %d |\n", n, anchor(n), len(groups[n]))
	}
	p("| [shipped, but cannot be created](#shipped-but-cannot-be-created) | %d |\n", len(shipped))
	p("\n**%d** types did not ship. **%d** more ship without a create.\n", len(notShipped), len(shipped))

	for _, n := range names {
		g := groups[n]
		sort.Slice(g, func(i, j int) bool { return g[i].Subject < g[j].Subject })
		p("\n## %s\n\n", n)
		p("%s\n\n", explain(n))
		p("| Type | Tier | Detail |\n| --- | --- | --- |\n")
		for _, w := range g {
			p("| `%s` | %s | %s |\n", w.Subject, strings.TrimPrefix(w.Tier, "tier"), cell(detail(w.Reason), 200))
		}
	}

	if len(shipped) > 0 {
		sort.Slice(shipped, func(i, j int) bool { return shipped[i].Subject < shipped[j].Subject })
		p("\n## Shipped, but cannot be created\n\n")
		p("These types **are** in the reference. They read, import, discover and delete. ")
		p("What they cannot do is create, because their create url has a placeholder nothing supplies — ")
		p("not an instance setting (project, region, zone, location), not a stored binding, and not a settable attribute of their own. ")
		p("The create is refused before a request is sent, rather than by Google answering a url with an empty segment in it.\n\n")
		p("| Type | Create url | Needs |\n| --- | --- | --- |\n")
		for _, w := range shipped {
			p("| `%s` | `%s` | %s |\n", w.Subject, code(w.Template), cell(strings.TrimPrefix(w.Reason, "needs "), 120))
		}
	}
	return b.String()
}

// explain gives each group the sentence a reader needs to know what to do next.
// An unrecognised category still gets a row in the table; it just gets no extra
// sentence, so a new reason from the generator shows up rather than vanishing.
func explain(category string) string {
	switch category {
	case "unruled wire hooks":
		return "The upstream definition carries hooks that rewrite the request or response. " +
			"Each of these ships as soon as a ruling in `gen/overlay.yaml` names every hook on the row and says what it does."
	case "no insert or create method":
		return "The API publishes no way to create one. Most of these are read-only collections — locations, operations, supported flags — " +
			"that exist to be listed, not managed."
	case "no delete method":
		return "The API publishes no way to delete one. A type infrena cannot remove is a type it cannot honestly manage."
	case "magic-modules marks it exclude":
		return "Upstream excludes the resource from generation, so there is no definition to work from."
	case "min_version is beta, not ga":
		return "Only a beta API serves it. This plugin generates from GA surfaces."
	case "legacy alias of a type that does ship":
		return "An older url for a resource another type already serves, under the name in the Detail column. Use that type."
	case "no get method":
		return "The API publishes no get. Reading one means listing its parent, which needs a ruling with `read_via` in `gen/overlay.yaml`."
	}
	return "Reported by the generator."
}

