// attrRow is one attribute at one path.
type attrRow struct {
	Path string
	Attr *catalog.Attr
	// SameAs is the earlier path whose subtree is identical to this one's.
	// Several GCP schemas are recursive -- bigquery's standard SQL data type
	// nests into itself six deep -- and expanding each occurrence in full
	// turns one type's page into 3708 rows, most of them the same rows again.
	// The attribute is still listed; only the repeat of its subtree is not.
	SameAs string
}

// attrRows walks a type's whole attribute tree, depth first, in sorted order.
//
// It follows BOTH nesting edges. Fields is an object's attributes and Elem is a
// list's element, and they are not alternatives: measured on this catalog
// (2026-09-23), a walk that follows only Fields reaches 8017 of the 19730
// attribute paths -- it drops 59% of them, every one inside a repeated block.
// Anything that only knew about Fields would be silently, confidently wrong
// about the whole of GCP's list-of-object shape.
func attrRows(t *catalog.Type) []attrRow {
	var out []attrRow
	seen := map[string]string{}
	var walk func(path string, a *catalog.Attr)
	walk = func(path string, a *catalog.Attr) {
		row := attrRow{Path: path, Attr: a}
		if len(a.Fields) > 0 || a.Elem != nil {
			k := shape(a)
			if prev, ok := seen[k]; ok {
				row.SameAs = prev
				out = append(out, row)
				return
			}
			seen[k] = path
		}
		out = append(out, row)
		for _, n := range sortedKeys(a.Fields) {
			walk(path+"."+n, a.Fields[n])
		}
		if a.Elem != nil {
			walk(path+"[]", a.Elem)
		}
	}
	for _, n := range sortedKeys(t.Attributes) {
		walk(n, t.Attributes[n])
	}
	return out
}

// shape keys an attribute's whole subtree by content. encoding/json sorts map
// keys, so the same subtree hashes the same however it was built.
func shape(a *catalog.Attr) string {
	blob, err := json.Marshal(a)
	if err != nil {
		// An Attr is plain data with no channels, funcs or NaNs in it, so
		// this cannot happen; a unique key keeps the walk correct if it ever
		// does, rather than collapsing two different subtrees into one.
		return fmt.Sprintf("unmarshalable:%p", a)
	}
	sum := sha256.Sum256(blob)
	return hex.EncodeToString(sum[:])
}

func sortedKeys(m map[string]*catalog.Attr) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// spellings is every name configuration accepts for the attribute, plus the
// wire name when it differs from the schema name (307 attributes in this
// catalog, e.g. the schema's `type_value` for the wire's `type`).
func (r attrRow) spellings() string {
	if strings.HasSuffix(r.Path, "[]") {
		// A list element has no name of its own; it carries its list's.
		return "—"
	}
	key := r.Path
	if i := strings.LastIndexAny(key, "."); i >= 0 {
		key = key[i+1:]
	}
	var parts []string
	for _, a := range r.Attr.Aliases {
		if a != key {
			parts = append(parts, "`"+a+"`")
		}
	}
	if c := r.Attr.Canonical; c != "" && c != key {
		parts = append(parts, "wire `"+c+"`")
	}
	if len(parts) == 0 {
		return "—"
	}
	return strings.Join(parts, ", ")
}

func (r attrRow) notes() string {
	var n []string
	if r.Attr.ForceNew {
		n = append(n, "force new")
	}
	if r.Attr.CreateOnly {
		n = append(n, "create only")
	}
	if r.Attr.Sensitive {
		n = append(n, "sensitive")
	}
	if r.Attr.Opaque {
		n = append(n, "opaque")
	}
	if r.Attr.Unordered {
		n = append(n, "unordered")
	}
	if r.Attr.Ref != nil {
		n = append(n, fmt.Sprintf("refers to `%s.%s`", r.Attr.Ref.Type, r.Attr.Ref.Attribute))
	}
	if r.SameAs != "" {
		n = append(n, fmt.Sprintf("same fields as `%s`", r.SameAs))
	}
	if len(n) == 0 {
		return "—"
	}
	return strings.Join(n, ", ")
}

func refRows(rows []attrRow) []attrRow {
	var out []attrRow
	for _, r := range rows {
		if r.Attr.Ref != nil {
			out = append(out, r)
		}
	}
	return out
}

func setBy(a *catalog.Attr) string {
	switch {
	case a.Output:
		return "output only"
	case a.Required:
		return "required"
	default:
		return "optional"
	}
}

// canCreate asks the same question catalog.Definitions asks when it tells the
// host what a type can do. One rule, two readers.
func canCreate(t *catalog.Type) bool { return len(t.UnresolvedCreatePlaceholders()) == 0 }

