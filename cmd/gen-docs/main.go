// Command gen-docs writes the public type reference under docs/reference from
// the embedded catalog and gen/warnings.txt.
//
// The pages are COMMITTED, and cmd/gen-docs is the only thing allowed to write
// them. A page hand-edited to say something the catalog does not say is worse
// than no page: the catalog is what the plugin actually serves. main_test.go
// fails when what is committed differs from what this command would write, so a
// regeneration nobody committed is a red build rather than a quiet drift.
//
// Everything here sorts before it iterates. A docs generator that reorders its
// own output between runs makes every regeneration an unreviewable diff, and
// Go's map iteration order is deliberately random, so "it looked stable" is not
// evidence. TestRenderingIsDeterministic re-renders and compares.
package main

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/infrena/infrena-provider-gcp/internal/catalog"
)

func main() {
	out := flag.String("out", "docs/reference", "directory to write the reference into")
	warnPath := flag.String("warnings", "gen/warnings.txt", "the generator's warnings file")
	check := flag.Bool("check", false, "do not write; exit non-zero if what is on disk differs")
	flag.Parse()

	c, err := catalog.Load()
	if err != nil {
		log.Fatalf("gen-docs: load catalog: %v", err)
	}
	raw, err := os.ReadFile(*warnPath)
	if err != nil {
		log.Fatalf("gen-docs: %v", err)
	}
	ws, err := parseWarnings(string(raw))
	if err != nil {
		log.Fatalf("gen-docs: %s: %v", *warnPath, err)
	}

	pages := Pages(c, ws)
	if *check {
		diff, err := compare(*out, pages)
		if err != nil {
			log.Fatalf("gen-docs: %v", err)
		}
		if len(diff) > 0 {
			for _, d := range diff {
				fmt.Fprintln(os.Stderr, d)
			}
			log.Fatalf("gen-docs: %d page(s) out of date; run `go run ./cmd/gen-docs`", len(diff))
		}
		fmt.Printf("gen-docs: %d pages up to date\n", len(pages))
		return
	}
	if err := write(*out, pages); err != nil {
		log.Fatalf("gen-docs: %v", err)
	}
	fmt.Printf("gen-docs: wrote %d pages for %d types\n", len(pages), len(c.Types))
}

// ---------------------------------------------------------------------------
// warnings
// ---------------------------------------------------------------------------

// warning is one row of gen/warnings.txt. The file is tab-separated and has
// two shapes: three fields for a type that did not ship (tier, product/Resource,
// reason) and four for one that ships without create (nocreate, type, create
// template, missing placeholders).
type warning struct {
	Tier     string
	Subject  string
	Template string
	Reason   string
}

// parseWarnings reads the file. It REFUSES a row it does not understand rather
// than skipping it, because the whole point of not-shipped.md is that nothing
// disappears quietly between the generator and the reader.
func parseWarnings(text string) ([]warning, error) {
	var ws []warning
	sc := bufio.NewScanner(strings.NewReader(text))
	for line := 1; sc.Scan(); line++ {
		s := sc.Text()
		if strings.TrimSpace(s) == "" || strings.HasPrefix(s, "#") {
			continue
		}
		f := strings.Split(s, "\t")
		switch len(f) {
		case 3:
			ws = append(ws, warning{Tier: f[0], Subject: f[1], Reason: f[2]})
		case 4:
			ws = append(ws, warning{Tier: f[0], Subject: f[1], Template: f[2], Reason: f[3]})
		default:
			return nil, fmt.Errorf("line %d: %d tab-separated fields, want 3 or 4: %q", line, len(f), s)
		}
	}
	return ws, sc.Err()
}

// category collapses a reason to the group it belongs in. The detail after a
// ":" or ";" is the part that differs per type (which hooks, which method), and
// it stays on the row; the part in front is what the grouping is for.
func category(reason string) string {
	if i := strings.IndexAny(reason, ":;"); i >= 0 {
		return strings.TrimSpace(reason[:i])
	}
	if strings.HasPrefix(reason, "legacy alias of ") {
		return "legacy alias of a type that does ship"
	}
	return reason
}

// detail is the per-row remainder: what category left behind.
func detail(reason string) string {
	if i := strings.IndexAny(reason, ":;"); i >= 0 {
		return strings.TrimSpace(reason[i+1:])
	}
	if strings.HasPrefix(reason, "legacy alias of ") {
		return strings.TrimPrefix(reason, "legacy alias of ")
	}
	return ""
}

