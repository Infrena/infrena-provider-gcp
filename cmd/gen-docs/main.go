func scopeName(s catalog.Scope) string {
	switch s {
	case catalog.ScopeRegional:
		return "regional"
	case catalog.ScopeZonal:
		return "zonal"
	default:
		return "global"
	}
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "**no**"
}

func orElse(s, fallback string) string {
	if s != "" {
		return s
	}
	return fallback
}

func paren(s string) string {
	if s == "" {
		return ""
	}
	return " (" + s + ")"
}

func list(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = "`" + s + "`"
	}
	return strings.Join(q, ", ")
}

// flatten turns a multi-line upstream description into one line a table cell
// can hold, with the characters that would be read as markup escaped.
//
// Brackets are escaped too, which looks fussy until you read what is actually
// in these descriptions: url templates carrying "[a-z0-9-]{0,61}[a-z0-9]" and
// prose carrying "[the Airflow web interface](/composer/docs/...)". Left alone,
// the first renders as an empty link and the second as a link relative to
// whatever is hosting this page -- a 404 that looks like the plugin's fault.
// A description is data. Nothing in it is markup.
func flatten(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	r := strings.NewReplacer(
		"|", "\\|",
		"<", "&lt;",
		"[", "\\[",
		"]", "\\]",
	)
	return r.Replace(s)
}

// code escapes a template for a code span. A `|` inside one still ends a table
// cell, backticks and all.
func code(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// cell truncates at a word boundary. Upstream descriptions run to paragraphs,
// and a table whose rows are paragraphs is a table nobody reads.
func cell(s string, max int) string {
	if s == "" {
		return "—"
	}
	if len(s) <= max {
		return s
	}
	cut := s[:max]
	if i := strings.LastIndex(cut, " "); i > max/2 {
		cut = cut[:i]
	}
	return strings.TrimRight(cut, " .,;:") + " …"
}

func firstSentence(s string) string {
	s = flatten(s)
	if i := strings.Index(s, ". "); i >= 0 {
		return s[:i+1]
	}
	return s
}

// anchor is GitHub's heading slug, for the summary table's links.
func anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case r == '_':
			// GitHub's slugger drops punctuation but KEEPS an underscore, so
			// "min_version is beta" anchors at "min_version-is-beta". Folding
			// it to a hyphen here would produce links that scroll nowhere.
			b.WriteRune('_')
		case r == ' ' || r == '-':
			b.WriteRune('-')
		}
	}
	return b.String()
}

