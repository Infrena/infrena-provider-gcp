// write puts every page on disk and removes any .md under the root that this
// run did not produce. A page for a type that no longer exists is a page that
// lies, and leaving it behind is how a reference outlives its catalog.
func write(root string, pages map[string]string) error {
	for _, rel := range sortedPages(pages) {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(pages[rel]), 0o644); err != nil {
			return err
		}
	}
	return prune(root, pages)
}

func prune(root string, pages map[string]string) error {
	return filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".md") {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		if _, ok := pages[filepath.ToSlash(rel)]; !ok {
			return os.Remove(path)
		}
		return nil
	})
}

// compare reports every page that is missing, stale or left over. It returns
// the differences rather than the first one, because "regenerate and commit" is
// one action whatever the count.
func compare(root string, pages map[string]string) ([]string, error) {
	var diff []string
	for _, rel := range sortedPages(pages) {
		got, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if os.IsNotExist(err) {
			diff = append(diff, "missing: "+rel)
			continue
		}
		if err != nil {
			return nil, err
		}
		if string(got) != pages[rel] {
			diff = append(diff, "out of date: "+rel)
		}
	}
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) && path == root {
				return nil
			}
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".md") {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		if _, ok := pages[filepath.ToSlash(rel)]; !ok {
			diff = append(diff, "left over: "+filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(diff)
	return diff, nil
}

func sortedPages(pages map[string]string) []string {
	out := make([]string, 0, len(pages))
	for k := range pages {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
